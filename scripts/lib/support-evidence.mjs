import { readFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";
import { ROUTE_SCHEMA_CATALOG, findRouteSchema } from "../../src/adapters/route-schemas.js";
import { assessReplay, checkCapture, resetDifferences, scenarioDigest } from "./live-acceptance.mjs";

export async function loadAcceptanceInputs(root) {
  const routes = JSON.parse(await readFile(resolve(root,"tests/fixtures/live-route-cases.json"),"utf8"));
  const definitions = JSON.parse(await readFile(resolve(root,"docs/acceptance/scenarios.json"),"utf8"));
  const scenarios = definitions.map((scenario) => {
    const contract = routes.find((item) => item.schema === scenario.schemaId);
    if (!contract) throw new Error(`Missing route contract: ${scenario.schemaId}`);
    const filteredUrl = new URL(contract.url);
    for (const key of contract.removed || []) filteredUrl.searchParams.delete(key);
    const resetUrl = new URL(scenario.resetUrl);
    if (filteredUrl.origin !== resetUrl.origin || filteredUrl.protocol !== "https:") throw new Error("Scenario origin mismatch");
    if (findRouteSchema(filteredUrl)?.id !== scenario.schemaId) throw new Error("Scenario schema mismatch");
    if (!scenario.expectedCriteria?.length) throw new Error("Scenario has no expected criteria");
    return {...scenario,filteredUrl:filteredUrl.toString()};
  });
  if (new Set(scenarios.map((item) => item.id)).size !== scenarios.length) throw new Error("Duplicate acceptance scenario");
  for (const schema of ROUTE_SCHEMA_CATALOG) {
    if (!routes.some((item) => item.schema === schema.id)) throw new Error(`Missing route fixture: ${schema.id}`);
  }
  return {catalog:ROUTE_SCHEMA_CATALOG,routes,scenarios};
}

export function validateAcceptanceRecord(record, scenarios) {
  if (record.formatVersion !== 1 || record.environment !== "live") throw new Error("Invalid acceptance record format");
  if (!/^\d+\.\d+\.\d+$/.test(record.source?.version || "")) throw new Error("Missing source version");
  if (!/^[a-f0-9]{64}$/.test(record.source?.runtimeSha256 || "")) throw new Error("Missing runtime fingerprint");
  if (!Number.isFinite(Date.parse(record.checkedAt))) throw new Error("Invalid acceptance date");
  if (record.permissionMode !== "isolated-test-origins") throw new Error("Unknown permission mode");
  if (!record.cases?.length || record.cases.length > scenarios.length) throw new Error("Invalid acceptance cases");
  if (new Set(record.cases.map((item) => item.scenarioId)).size !== record.cases.length) throw new Error("Duplicate acceptance evidence");
  for (const item of record.cases) {
    const scenario = scenarios.find((entry) => entry.id === item.scenarioId);
    if (!scenario || item.schemaId !== scenario.schemaId || !Number.isInteger(item.schemaVersion)) throw new Error("Unknown acceptance scenario");
    if (!/^[a-f0-9]{64}$/.test(item.scenarioSha256 || "")) throw new Error("Invalid scenario fingerprint");
    if (!["PASS","PARTIAL","FAIL","BLOCKED"].includes(item.status)) throw new Error("Unknown acceptance outcome");
    if (typeof item.reason !== "string" || !item.reason || item.reason.length > 500) throw new Error("Missing acceptance reason");
    if (item.status !== "PASS") continue;
    if (!Number.isInteger(item.omissions) || item.omissions < 0) throw new Error("Missing capture omission count");
    if (item.stage !== "COMPLETE" || item.savedRoundTrip !== true) throw new Error("Pass without completed save and replay");
    if (!Array.isArray(item.resetCriteria)) throw new Error("Missing reset capture evidence");
    if (item.scenario?.schemaId !== item.schemaId || scenarioDigest(item.scenario) !== item.scenarioSha256) throw new Error("Invalid scenario evidence");
    checkCapture(item.capturedCriteria,item.scenario.expectedCriteria);
    const changed = resetDifferences(item.capturedCriteria,item.resetCriteria || []);
    if (!changed.length || JSON.stringify([...changed].sort()) !== JSON.stringify([...(item.resetChanged || [])].sort())) throw new Error("Pass without demonstrated reset");
    if (assessReplay(item.capturedCriteria,item.replay,item.omissions).status !== "PASS") throw new Error("Pass without criterion verification");
  }
  return record;
}

export async function loadAcceptanceRecords(root, scenarios) {
  const directory = resolve(root,"docs/acceptance/records");
  let names;
  try { names = await readdir(directory); } catch (error) { if (error.code === "ENOENT") return []; throw error; }
  const records = [];
  for (const name of names.filter((item) => item.endsWith(".json")).sort()) {
    const record = validateAcceptanceRecord(JSON.parse(await readFile(resolve(directory,name),"utf8")),scenarios);
    records.push({...record,path:`acceptance/records/${name}`});
  }
  return records;
}

export function renderSupportMatrix({catalog,routes,scenarios,records,source}) {
  const lines = ["# Storefront support evidence", "", "Generated by `npm run support:update`. Route fixtures and live acceptance are separate evidence.", "", `Runtime source fingerprint: \`${source.runtimeSha256}\`.`, "", "A live pass covers only the recorded scenario, source fingerprint, and date. Test copies receive access to the named retailer origin in an isolated profile. These records do not certify the production permission prompt or every filter on a retailer.", "", "| Storefront | Route schema | Route fixture | Latest live scenario evidence |", "|---|---|---|---|"];
  for (const schema of catalog) {
    const contract = routes.find((item) => item.schema === schema.id);
    const relevant = records.flatMap((record) => record.cases.filter((item) => item.schemaId === schema.id).map((item) => ({record,item}))).sort((a,b) => b.record.checkedAt.localeCompare(a.record.checkedAt));
    const latest = relevant[0];
    let evidence = scenarios.some((item) => item.schemaId === schema.id) ? "Scenario ready, not run" : "Not run";
    if (latest) {
      const {record,item} = latest;
      const scenario = scenarios.find((entry) => entry.id === item.scenarioId);
      const current = record.source.runtimeSha256 === source.runtimeSha256 ? record.source.version === source.version ? item.schemaVersion === schema.version : false : false;
      const scenarioCurrent = scenario ? item.scenarioSha256 === scenarioDigest(scenario) : false;
      const status = current ? scenarioCurrent ? item.status : "STALE" : "STALE";
      const reason = item.reason.replaceAll("|","/").replace(/[\r\n]/g," ").replace(/[<>`\[\]]/g,"");
      evidence = `[${status}, ${record.checkedAt.slice(0,10)}](${record.path}): ${reason}`;
    }
    lines.push(`| ${contract.shop} | ${schema.id} v${schema.version} | Covered | ${evidence} |`);
  }
  lines.push("", "A stale record remains historical evidence and cannot establish support for the current source. A blocked or partial run never becomes a pass. Runtime page-level support labels are distinct from this dated acceptance matrix.", "");
  return lines.join("\n");
}
